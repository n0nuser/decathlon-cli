// docsgen renders the command reference for docs-site from the cobra tree,
// one page per top-level command. CI regenerates it and fails on a diff, so
// the published flags are always the binary's flags.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"

	"github.com/n0nuser/decathlon-cli/internal/cli"
)

const banner = "{/* Generated by cmd/docsgen. Edit the cobra help text, then run `make docs`. */}\n\n"

func main() {
	dir := flag.String("out", "docs-site/content/docs/reference", "output directory")
	flag.Parse()
	root := cli.CommandTree("0.0.0")
	if err := os.MkdirAll(*dir, 0o755); err != nil {
		die(err)
	}
	if err := clean(*dir); err != nil {
		die(err)
	}
	pages := []string{"index", "global-flags"}
	var g strings.Builder
	g.WriteString("---\ntitle: Global flags\ndescription: Flags every command accepts.\n---\n\n" + banner)
	flags(&g, root.PersistentFlags())
	write(filepath.Join(*dir, "global-flags.mdx"), g.String())

	var top []*cobra.Command
	for _, c := range root.Commands() {
		if !c.Hidden && c.Name() != "help" && c.Name() != "completion" {
			top = append(top, c)
		}
	}
	sort.Slice(top, func(i, j int) bool { return top[i].Name() < top[j].Name() })
	for _, c := range top {
		var b strings.Builder
		fmt.Fprintf(&b, "---\ntitle: %s\ndescription: %s\n---\n\n%s", c.Name(), quote(c.Short), banner)
		var walk func(c *cobra.Command, level int)
		walk = func(c *cobra.Command, level int) {
			section(&b, c, level)
			for _, sub := range c.Commands() {
				if !sub.Hidden && sub.Name() != "help" {
					walk(sub, min(level+1, 4))
				}
			}
		}
		walk(c, 2)
		write(filepath.Join(*dir, c.Name()+".mdx"), b.String())
		pages = append(pages, c.Name())
	}
	meta, _ := json.MarshalIndent(map[string]any{"title": "Command reference", "pages": pages}, "", "  ")
	write(filepath.Join(*dir, "meta.json"), string(meta)+"\n")
	fmt.Fprintf(os.Stderr, "docsgen: %d pages in %s\n", len(pages)-1, *dir)
}

// clean removes what an earlier run generated; the hand-written index.mdx stays.
func clean(dir string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		n := e.Name()
		if n != "index.mdx" && (strings.HasSuffix(n, ".mdx") || n == "meta.json") {
			if err := os.Remove(filepath.Join(dir, n)); err != nil {
				return err
			}
		}
	}
	return nil
}

func section(b *strings.Builder, c *cobra.Command, level int) {
	fmt.Fprintf(b, "%s `%s`\n\n", strings.Repeat("#", level), c.CommandPath())
	if c.Short != "" {
		b.WriteString(mdx(c.Short) + "\n\n")
	}
	if c.Runnable() {
		fmt.Fprintf(b, "```bash\n%s\n```\n\n", c.UseLine())
	}
	if long := strings.TrimSpace(c.Long); long != "" {
		prose, examples, _ := strings.Cut(long, "Examples:")
		if p := strings.TrimSpace(prose); p != "" && p != c.Short {
			b.WriteString(proseBlock(p) + "\n\n")
		}
		if ex := strings.TrimSpace(examples); ex != "" {
			var lines []string
			for _, l := range strings.Split(ex, "\n") {
				if t := strings.TrimSpace(l); t != "" {
					lines = append(lines, t)
				}
			}
			fmt.Fprintf(b, "```bash\n%s\n```\n\n", strings.Join(lines, "\n"))
		}
	}
	if len(c.Aliases) > 0 {
		fmt.Fprintf(b, "Aliases: `%s`\n\n", strings.Join(c.Aliases, "`, `"))
	}
	flags(b, c.LocalNonPersistentFlags())
}

// proseBlock keeps indented lines (config snippets, cron lines) as code.
func proseBlock(p string) string {
	var out []string
	var code []string
	flush := func() {
		if len(code) > 0 {
			out = append(out, "```\n"+strings.Join(code, "\n")+"\n```")
			code = nil
		}
	}
	for _, l := range strings.Split(p, "\n") {
		if strings.HasPrefix(l, "  ") {
			code = append(code, strings.TrimPrefix(l, "  "))
			continue
		}
		flush()
		out = append(out, mdx(l))
	}
	flush()
	return strings.Join(out, "\n")
}

func flags(b *strings.Builder, fs *pflag.FlagSet) {
	var rows []string
	fs.VisitAll(func(f *pflag.Flag) {
		if f.Hidden {
			return
		}
		def := "-"
		if f.DefValue != "" && f.DefValue != "[]" {
			def = "`" + f.DefValue + "`"
		}
		rows = append(rows, fmt.Sprintf("| `--%s` | %s | %s | %s |", f.Name, f.Value.Type(), def, mdx(strings.ReplaceAll(f.Usage, "|", "\\|"))))
	})
	if len(rows) == 0 {
		return
	}
	b.WriteString("| Flag | Type | Default | Description |\n| --- | --- | --- | --- |\n" + strings.Join(rows, "\n") + "\n\n")
}

// mdx escapes what MDX would parse as JSX or expressions.
func mdx(s string) string { return strings.NewReplacer("{", "\\{", "}", "\\}", "<", "\\<").Replace(s) }

func quote(s string) string { return strings.ReplaceAll(fmt.Sprintf("%q", s), ` `, " ") }

func write(path, s string) {
	if err := os.WriteFile(path, []byte(s), 0o644); err != nil {
		die(err)
	}
}

func die(err error) {
	fmt.Fprintln(os.Stderr, "docsgen:", err)
	os.Exit(1)
}
